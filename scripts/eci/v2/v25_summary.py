"""
ECI v2.5 summary: reads OUT25/{mice,ants}/report.json, OUT25/train/*.json, the identity report and the sheet verdicts
(OUT25/figures/visual.json, written by hand after looking at the sheets) -> OUT25/summary.json, OUT25/summary.md.
Criteria exactly as scripts/eci/v2/v25_prereg.md (A numeric part + visual part, B, ants non-inferiority, deploy).
"""
import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
REPO = Path(__file__).resolve().parents[3]
OUT = REPO / 'results/vision/eci_v2_5'
ARMS = ('N0', 'W1', 'Wh', 'C1', 'M2')
MOTION = ('W1', 'Wh', 'C1', 'M2')
RULES = ('auc', 'dist', 'dist2048')
NAME = {'nose_nose': 'nose-nose', 'nt': 'nose-tail', 'groom_any': 'grooming-to-focal (any)'}


def f3(lv, d=3):
    return f"{lv['mean']:.{d}f} [{lv['ci'][0]:.{d}f}, {lv['ci'][1]:.{d}f}]"


def c3(c, d=3):
    return f"{c['diff']:+.{d}f} [{c['ci'][0]:+.{d}f}, {c['ci'][1]:+.{d}f}]"


def main():
    M = json.loads((OUT / 'mice' / 'report.json').read_text())
    A = json.loads((OUT / 'ants' / 'report.json').read_text())
    vis = json.loads((OUT / 'figures' / 'visual.json').read_text()) if (OUT / 'figures' / 'visual.json').exists() else {}
    a2b = A['dirs']['A2B']
    S = {'criteria': {}, 'B': {}, 'ants_NI': {}}
    # ---- ants non-inferiority (arm - V, A -> B)
    for arm in ARMS:
        c = a2b['contrasts'].get(f'{arm} - V', {}).get('groom_any|auc')
        if c:
            S['ants_NI'][arm] = {'AUROC diff': c['diff'], 'lower CI': c['ci'][0], 'pass': c['ci'][0] >= -0.02}
    # ---- A (numeric) per arm / rule
    vtop = M['levels']['V|auc']['nt|top3']['mean']
    for arm in ARMS:
        for r in RULES:
            k = f'{arm}|{r}'
            c = M['contrasts'].get(f'{k} - V|auc')
            if not c:
                continue
            dd = M['distinct'][k]
            nt3 = M['levels'][k]['nt|top3']['mean']
            a = {'distinct': f'{dd[0]}/{dd[1]}', 'A1 distinct 3/3': dd[0] == dd[1] == 3,
                 'nose-tail top3': nt3, 'V nose-tail top3': vtop, 'A2 nose-tail top3 >= V': nt3 >= vtop,
                 'nose-tail AUROC lower CI vs V': c['nt|auc']['ci'][0], 'A3 nose-tail AUROC LCI >= -0.02': c['nt|auc']['ci'][0] >= -0.02,
                 'nose-nose AUROC lower CI vs V': c['nose_nose|auc']['ci'][0], 'A4 nose-nose AUROC LCI >= -0.03': c['nose_nose|auc']['ci'][0] >= -0.03,
                 'nose-nose top3 lower CI vs V': c['nose_nose|top3']['ci'][0], 'A5 nose-nose top3 LCI >= -0.08': c['nose_nose|top3']['ci'][0] >= -0.08}
            a['A numeric'] = all(a[x] for x in a if x.startswith('A') and x[1].isdigit())
            v = vis.get(k)
            a['A6 sheet'] = v
            a['A'] = bool(a['A numeric'] and v is not None and v.get('labelled', 0) >= 3 and v.get('plausible', False))
            S['criteria'][k] = a
    # ---- B per motion arm / mice rule
    for arm in MOTION:
        if f'{arm} - N0' not in a2b['contrasts']:
            continue
        ca = a2b['contrasts'][f'{arm} - N0']
        for r in RULES[:2]:
            cm = M['contrasts'][f'{arm}|{r} - N0|{r}']
            mets = {'mice nose-tail AUROC': cm['nt|auc'], 'mice nose-tail top3': cm['nt|top3'], 'ants AUROC': ca['groom_any|auc'],
                    'ants top3': ca['groom_any|top3']}
            win = [m for m, c in mets.items() if c['ci'][0] > 0]
            ok = False
            for w in win:
                others = [m for m in mets if m != w and 'AUROC' in m]
                if all(mets[o]['ci'][0] >= -0.02 for o in others):
                    ok = True
            S['B'][f'{arm}|{r}'] = {'contrasts': {m: [c['diff'], c['ci'][0], c['ci'][1]] for m, c in mets.items()}, 'winning': win, 'pass': ok}
    # ---- deploy
    cand = []
    for k, a in S['criteria'].items():
        arm, r = k.split('|')
        if arm in MOTION and a['A'] and S['B'].get(k, {}).get('pass') and S['ants_NI'][arm]['pass']:
            cand.append((a['nose-tail top3'], -('C' in arm), k))
    S['deploy'] = max(cand)[2] if cand else None
    S['deploy_candidates'] = [c[2] for c in sorted(cand, reverse=True)]
    # ---- training health
    tr = {}
    for p in sorted((OUT / 'train').glob('*_s25*.json')):
        j = json.loads(p.read_text())
        tr[p.stem] = {'eval_fve': j['eval_fve'], 'l0': j['eval_l0'], 'dead_frac': j['dead_frac_at_end_train'], 'never_fire_eval': j['never_fire_on_eval_frac'],
                      'steps': j['steps_run'], 'passes': j['passes'], 'train_time_s': j['train_time_s'], 'gpu_util_median': j['gpu_util_median']}
    S['train'] = tr
    (OUT / 'summary.json').write_text(json.dumps(S, indent=1, default=float))
    # ---- markdown tables
    md = ['# ECI v2.5 tables (generated by scripts/eci/v2/v25_summary.py)', '']
    md += ['## Mice (select on SG 11 pools, measure on 12 non-SG pools; edge-excluded ext frames)', '']
    cn = M['counts']
    for b in ('nose_nose', 'nt'):
        c = cn[b]
        md.append(f"- {NAME[b]}: held-out {c['held_out_frames']:,} frames / {c['held_out_videos']} videos, {c['positive_frames']:,} positive "
                  f"(prevalence {c['prevalence']:.4f}); top3 eligible videos {c['top3_eligible_videos']}; edge rule removed "
                  f"{c['edge_removed_frames_all']} frames ({c['edge_removed_positives_all']} positive) of all scored, "
                  f"{c['edge_removed_frames_held_out']} ({c['edge_removed_positives_held_out']} positive) of the held-out set")
    md += ['', '| model rule | nose-nose AUROC | nose-nose precision@top3/video (chance) | nose-tail AUROC | nose-tail precision@top3/video (chance) | '
           'distinct picks | nose-tail discrimination AUROC | nose-nose per-video MAE, s | nose-tail per-video MAE, s | nose-tail Pearson r time | '
           'top3 frames in first/last 2 s (nose-nose / nose-tail) |', '|' + '---|' * 11]
    for k, lv in M['levels'].items():
        if k.split('|')[1] == 'dist2048' and k.split('|')[0] in ('v1s0',):
            continue
        vd = M['video'][k]
        ef = M['edge_frac'][k]
        md.append(f"| {k} | {f3(lv['nose_nose|auc'])} | {f3(lv['nose_nose|top3'])} ({lv['nose_nose|chance']['mean']:.3f}) | {f3(lv['nt|auc'])} | "
                  f"{f3(lv['nt|top3'])} ({lv['nt|chance']['mean']:.3f}) | {M['distinct'][k][0]}/{M['distinct'][k][1]} | {lv['nt|disc']['mean']:.3f} | "
                  f"{vd['nose_nose']['raw_mae'][0]:.1f} +- {vd['nose_nose']['raw_mae'][1]:.1f} | {vd['nt']['raw_mae'][0]:.1f} +- {vd['nt']['raw_mae'][1]:.1f} | "
                  f"{lv['nt|r_soft']['mean']:.2f} | {np.mean(ef['nose_nose']):.3f} / {np.mean(ef['nt']):.3f} |")
    md += ['', '### Mice contrasts', '', '| contrast | nose-nose AUROC | nose-nose precision@top3/video | nose-tail AUROC | nose-tail precision@top3/video | paired |', '|---|---|---|---|---|---|']
    for k, c in M['contrasts'].items():
        md.append(f"| {k} | {c3(c['nose_nose|auc'])} | {c3(c['nose_nose|top3'])} | {c3(c['nt|auc'])} | {c3(c['nt|top3'])} | {c['nt|auc']['paired']} |")
    md += ['', f"dist constraint binds (seeds where the dist nose-tail pick != the auc pick): {M['dist_binds']}", '']
    for dn, R in A['dirs'].items():
        md += [f'## Ants grooming-to-focal (any), {dn} ({"PRIMARY" if dn == "A2B" else "swapped"})', '',
               f"held-out {R['held_out']['frames']:,} frames / {R['held_out']['videos']} videos, {R['held_out']['positive_frames']:,} positive "
               f"(prevalence {R['prevalence']:.4f}); top3 eligible {R['top3_counts']['eligible']} of {R['top3_counts']['held_out_videos']} videos", '',
               '| model | AUROC | precision@top3/video (chance) | precision@100 | per-video MAE, s (raw) | Pearson r time | top3 frames in first 2 s |', '|---|---|---|---|---|---|---|']
        for k, lv in R['levels'].items():
            vd = R['video'][k]
            md.append(f"| {k} | {f3(lv['groom_any|auc'])} | {f3(lv['groom_any|top3'])} ({lv['groom_any|chance']['mean']:.3f}) | {f3(lv['groom_any|p100'])} | "
                      f"{vd['raw_mae'][0]:.1f} +- {vd['raw_mae'][1]:.1f} | {lv['groom_any|r_soft']['mean']:.2f} | {np.nanmean(R['edge_frac'][k]):.3f} |")
        md += ['', '| contrast | AUROC | precision@top3/video | paired |', '|---|---|---|---|']
        for k, c in R['contrasts'].items():
            md.append(f"| {k} | {c3(c['groom_any|auc'])} | {c3(c['groom_any|top3'])} | {c['groom_any|auc']['paired']} |")
        md.append('')
    md += ['## Criteria', '', '```', json.dumps({k: v for k, v in S.items() if k != 'train'}, indent=1, default=float), '```', '',
           '## SAE health', '', '| key | eval FVE | L0 | dead frac | never fire (eval) | steps | passes |', '|---|---|---|---|---|---|---|']
    for k, t in tr.items():
        md.append(f"| {k} | {t['eval_fve']:.4f} | {t['l0']:.2f} | {t['dead_frac']:.4f} | {t['never_fire_eval']:.4f} | {t['steps']:,} | {t['passes']:.2f} |")
    (OUT / 'tables.md').write_text('\n'.join(md) + '\n')
    print(json.dumps({k: v for k, v in S.items() if k != 'train'}, indent=1, default=float))


if __name__ == '__main__':
    main()
